console.log('Companies: never lose money by design');
let bad = 0;
for (const cat of COMPANY_CATEGORIES) for (let level = 1; level <= 3; level++) for (let eff = 0; eff <= 3; eff++) {
  const staff = COMPANY.capacity[level - 1], br = COMPANY.branchCap[level - 1];
  for (const mkt of [false, true]) {
    const co = { id: 'x', name: 'x', logo: '🏢', categoryId: cat.id, description: '', hqCity: 'lagos', level, efficiency: eff, manager: { hiredAt: 0 }, employees: Array.from({ length: staff }, (_, i) => ({ id: String(i), role: cat.roles[0], branchId: 'hq', hiredAt: 0 })), branches: Array.from({ length: br }, (_, i) => ({ id: String(i), cityId: 'lagos', label: 'b', openedAt: 0 })), campaigns: mkt ? MARKETING.map((m) => ({ id: m.id, channelId: m.id, startedAt: 0, endsAt: 9e9 })) : [], funds: 0, createdAt: 0, lifetime: { revenue: 0, payroll: 0, opex: 0, marketing: 0, investment: 0, payouts: 0 }, lastDayResult: null, lastDay: 0, lastPayoutDay: -1, activity: [] };
    if (C.dailyFigures(co as any, 1).net <= 0) bad++;
    for (const n of [0, 1, staff]) { if (C.dailyFigures({ ...co, employees: co.employees.slice(0, n), branches: [] } as any, 1).net <= 0) bad++; }
  }
}
