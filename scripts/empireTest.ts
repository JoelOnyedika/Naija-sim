registerContent();
let fails = 0;
const ok = (c: boolean, m: string) => { console.log(`${c ? '✓' : '✗'} ${m}`); if (!c) fails++; };
const eco = () => useEconomyStore.getState(), cs = () => useCompanyStore.getState().companies;
const setClock = (m: number) => useClockStore.setState({ minutes: m });
const fresh = (money: number) => { startNewLife('lapo'); clearGuard(); eco().reset(money); runDueEvents(); };
const count = (kind: string) => eco().transactions.filter((t) => t.kind === kind).length;
const NEW = { name: 'Mama Ife Kitchen', logo: '🍛', categoryId: 'food', description: 'Hot food, fast.', hqCity: 'lagos' };

console.log('Income tax (default rule)');
ok(INCOME_TAX.enabled, 'the tax rule is on');
ok(taxOn(0) === 0 && taxOn(150_000) === 0 && taxOn(600_000) === 22_500 && taxOn(2_000_000) === 162_500 && taxOn(3_000_000) === 312_500, 'brackets: 0% to 150k, 5% to 600k, 10% to 2M, 15% above (each rate only on its own slice)');
fresh(0);
setClock(100); eco().credit(1_000_000, 'Shift pay', 'salary'); eco().credit(500_000, 'Savings interest', 'interest'); eco().credit(300_000, 'Sold something', 'invest', undefined, { internal: true });
setClock(WEEK_MINUTES + 5); runDueEvents(); runDueEvents();
const t1 = useBankStore.getState().taxes.find((t) => t.id === 'w1')!;
ok(t1.taxable === 1_000_000 && t1.tax === taxOn(1_000_000) && t1.tax === 62_500 && t1.status === 'paid' && count('tax') === 1, 'only salary and business income is taxed (not interest or asset sales); charged once however often the run happens');
fresh(0); setClock(100); eco().credit(1_000_000, 'Shift pay', 'salary'); eco().debit(eco().money, 'spent it', 'purchase');
setClock(WEEK_MINUTES + 5); runDueEvents();
ok(useBankStore.getState().taxes[0].status === 'unpaid' && eco().money === 0 && count('tax') === 0, 'with no money the tax is recorded as unpaid, nothing negative');
eco().credit(500_000, 'bonus', 'income');
const before = eco().money;
ok(payTax('w1').ok && eco().money === before - 62_500 && !payTax('w1').ok, 'unpaid tax can be paid once');
fresh(0); setClock(100); eco().credit(1_000_000, 'Shift pay', 'salary'); eco().debit(eco().money, 'spent it', 'purchase');
setClock(WEEK_MINUTES + 5); runDueEvents(); eco().credit(500_000, 'income', 'income'); setClock(WEEK_MINUTES * 2 + 5); runDueEvents();
ok(useBankStore.getState().taxes.find((t) => t.id === 'w1')!.status === 'paid' && count('tax') === 1, 'unpaid tax is retried automatically at the next weekly run');

console.log('Land');
fresh(60_000_000);
const plot = PLOTS.find((p) => p.cityId === 'lagos')!, abuja = PLOTS.find((p) => p.cityId === 'abuja')!;
ok(PLOTS.length === 24 && new Set(PLOTS.map((p) => p.id)).size === 24 && PLOTS.every((p) => /^[a-z-]+\.plot-\d$/.test(p.id)), '24 plots over 4 cities with stable ids');
const nw0 = computeNetWorth().total;
ok(!buyPlot('nope').ok && buyPlot(plot.id).ok && eco().money === 60_000_000 - plot.price && !buyPlot(plot.id).ok, 'buying takes the price once; a second purchase is refused');
ok(computeNetWorth().total === nw0 && computeNetWorth().land === plot.price, 'net worth is unchanged by the purchase (wallet down, land up)');
ok(eco().lifetimeExpense === 0, 'buying land is an asset conversion, not an expense');
clearGuard(); eco().debit(eco().money - 1000, 'spend');
ok(!buyPlot(abuja.id).ok && !useLandStore.getState().owned[abuja.id], 'an unaffordable plot is refused and nothing is taken');
eco().credit(60_000_000, 'top up'); clearGuard();
ok(buyPlot(abuja.id).ok, 'a plot in another city can be bought');
useMapStore.getState().setState('abuja'); useMapStore.getState().setState('lagos');
ok(Object.keys(useLandStore.getState().owned).sort().join() === [plot.id, abuja.id].sort().join(), 'ownership survives switching city on the map');
const v0 = useLandStore.getState().owned[plot.id].value;
setClock(WEEK_MINUTES + 5); for (let i = 0; i < 4; i++) runDueEvents();
const v1 = useLandStore.getState().owned[plot.id].value;
ok(v1 === v0 + Math.floor((v0 * plot.growthBps) / 10_000) && v1 > v0, 'a plot appreciates by its weekly rate, once per week however often events run');
const money = eco().money;
clearGuard();
ok(sellPlot(plot.id).ok && eco().money === money + saleProceeds(v1) && saleProceeds(v1) < v1 && !sellPlot(plot.id).ok, 'selling pays the current value minus the fee, once');
ok(useLandStore.getState().realized === saleProceeds(v1) - plot.price, 'the realised gain or loss is recorded');
clearGuard();
ok(buyPlot(plot.id).ok && useLandStore.getState().owned[plot.id].value === plot.price, 'a sold plot can be bought again at the list price');

console.log('Companies: creating');
fresh(100_000_000);
ok(C.validateCreate({ ...NEW, name: 'ab' }) !== null && C.validateCreate({ ...NEW, logo: 'x' }) !== null && C.validateCreate({ ...NEW, categoryId: 'zzz' }) !== null && C.validateCreate({ ...NEW, hqCity: 'mars' }) !== null && C.validateCreate(NEW) === null, 'the create form is validated');
const startMoney = eco().money;
const cr = C.createCompany(NEW); 
ok(cr.ok && eco().money === startMoney - 2_500_000 && cs().length === 1, 'creating charges the startup cost once');
ok(!C.createCompany(NEW).ok && cs().length === 1, 'the same company cannot be created twice (tap guard or name)');
ok(cs()[0].funds === 0 && !C.isOperating(cs()[0]), 'a new company has no funds and is not operating');
clearGuard();
for (const n of ['Alpha Foods', 'Beta Foods', 'Gamma Foods']) { clearGuard(); C.createCompany({ ...NEW, name: n }); }
ok(cs().length === COMPANY.slots && !C.createCompany({ ...NEW, name: 'Fifth' }).ok, `at most ${COMPANY.slots} companies`);
fresh(100); ok(!C.createCompany(NEW).ok && cs().length === 0 && eco().money === 100, 'if you cannot afford it nothing is charged and nothing is created');

console.log('Companies: operating');
fresh(100_000_000); const id = (C.createCompany(NEW) as any).id as string; clearGuard();
const day0 = Math.floor(useClockStore.getState().minutes / DAY_MINUTES);
setClock((day0 + 1) * DAY_MINUTES + 5); runDueEvents();
ok(cs()[0].funds === 0 && cs()[0].lifetime.revenue === 0, 'a company without a manager earns no revenue');
ok(C.dailyFigures(cs()[0]).revenue === 0, 'its daily figures show no revenue until a manager is hired');
const w0 = eco().money;
ok(C.hireManager(id).ok && eco().money === w0 - 150_000 && !C.hireManager(id).ok && C.isOperating(cs()[0]), 'hiring the manager costs once; a second manager is refused');
clearGuard();
ok(C.hireEmployee(id, 'Cook').ok && !C.hireEmployee(id, 'Astronaut').ok && cs()[0].employees.length === 1, 'staff are hired by valid roles');
const f = C.dailyFigures(cs()[0]);
ok(f.revenue === 220_000 && f.payroll === 80_000 && f.net === 140_000, 'daily figures: (180k base + 40k per staff) revenue, 60k manager + 20k staff wages');
const walletBefore = eco().money;
setClock((day0 + 2) * DAY_MINUTES + 5); for (let i = 0; i < 4; i++) runDueEvents();
ok(cs()[0].funds === 140_000 && eco().money === walletBefore, 'a day settles once: revenue lands in company funds, and the personal wallet does not move');
ok(cs()[0].lifetime.revenue === 220_000 && cs()[0].lifetime.payroll === 80_000, 'revenue and payroll are tracked separately');
const nwBefore = computeNetWorth();
ok(nwBefore.companies === 140_000, 'company funds count in net worth once');
const income0 = eco().lifetimeIncome;
ok(C.cashOut(id).ok && eco().money === walletBefore + 140_000 && cs()[0].funds === 0 && eco().lifetimeIncome === income0 + 140_000, 'a payout moves the funds to the wallet exactly once and counts as income');
ok(computeNetWorth().total === nwBefore.total && !C.cashOut(id).ok, 'net worth is unchanged by the payout, and a second payout is refused (nothing to pay)');
clearGuard();
setClock((day0 + 3) * DAY_MINUTES + 5); runDueEvents();
ok(cs()[0].funds === 140_000, 'new funds arrive the next day');
ok(C.cashOut(id).ok, 'a payout is possible on a new game day');
ok(eco().transactions.filter((t) => t.ref?.type === 'company' && t.kind === 'business' && t.amount > 0).length === 2, 'the ledger shows exactly the two payouts');

console.log('Companies: levels, branches, marketing');
fresh(900_000_000); const c2 = (C.createCompany(NEW) as any).id as string; clearGuard();
const cap = (n: number) => { for (let i = 0; i < n; i++) { clearGuard(); C.hireEmployee(c2, 'Cook'); } };
ok(!C.openBranch(c2, 'abuja').ok, 'no branches at level 1');
ok(C.upgradeLevel(c2).ok === false, 'level 2 needs a manager and staff first');
C.hireManager(c2); clearGuard(); cap(4);
const m1 = eco().money;
ok(C.upgradeLevel(c2).ok && cs()[0].level === 2 && eco().money === m1 - 2_000_000, 'level 2 with a manager and 4 staff: charged once');
clearGuard(); cap(8); ok(cs()[0].employees.length === 12 && !C.hireEmployee(c2, 'Cook').ok, 'level 2 holds 12 staff, then hiring is refused (nothing charged)');
const wBefore = eco().money; clearGuard(); C.hireEmployee(c2, 'Cook'); ok(eco().money === wBefore, 'a refused hire costs nothing');
ok(!C.upgradeLevel(c2).ok, 'level 3 also needs a branch');
