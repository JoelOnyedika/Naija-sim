import { useVehicleStore } from '../src/stores/vehicleStore';
import { useGamesStore } from '../src/stores/gamesStore';
import { getDestination } from '../src/data/ride';

registerContent();
let fails = 0;
const ok = (c: boolean, m: string) => { console.log(`${c ? '✓' : '✗'} ${m}`); if (!c) fails++; };
const eco = () => useEconomyStore.getState(), G = () => useGroceryStore.getState(), st = () => useStatsStore.getState();
const fresh = (money = 100_000) => { startNewLife('lapo'); clearGuard(); eco().reset(money); st().apply({ energy: 100, hunger: 100, thirst: 100 }); };

console.log('Grocery catalogue');
ok(PRODUCTS.length >= 24 && new Set(PRODUCTS.map((p) => p.id)).size === PRODUCTS.length && PRODUCTS.every((p) => Number.isInteger(p.price) && p.price > 0), `${PRODUCTS.length} products with unique ids and whole-naira prices`);
ok(['rice', 'indomie', 'eggs', 'tomatopaste', 'cubes', 'oil', 'garri', 'beans', 'bread', 'yam', 'plantain', 'onions', 'tomatoes', 'peppers', 'beef', 'fish'].every((id) => PRODUCTS.some((p) => p.id === id)), 'the brief\'s Nigerian staples are all there');
console.log('Cart');
fresh();
ok(addToCart('rice').ok && addToCart('rice').ok && G().cart.rice === 2 && !addToCart('nope').ok, 'add to cart increments; unknown product refused');
ok(!setQty('rice', 21).ok && !setQty('rice', -1).ok && G().cart.rice === 2 && setQty('rice', 0).ok && !('rice' in G().cart), `quantity is limited to ${GROCERY.maxPerLine}; zero removes the line`);
setQty('rice', 2); setQty('eggs', 1);
let t = cartTotals();
ok(t.subtotal === 2 * 9_500 + 4_600 && t.lines.length === 2 && t.lines[0].lineTotal === t.lines[0].qty * t.lines[0].unitPrice && t.total === t.subtotal + t.delivery, 'line totals, subtotal and total add up');
ok(t.delivery === 0, 'delivery is free at or above the threshold');
clearCart(); setQty('salt', 2); t = cartTotals();
ok(t.subtotal === 800 && t.delivery === GROCERY.deliveryFee && t.total === 1_500, 'small orders pay the defined delivery fee');
clearCart(); ok(cartTotals().total === 0 && cartTotals().delivery === 0, 'an empty cart costs nothing');
console.log('Checkout');
fresh(20_000); setQty('rice', 2); setQty('beef', 2);   // 34,000
const before = eco().money, n0 = eco().transactions.length;
ok(!checkout().ok && eco().money === before && eco().transactions.length === n0 && G().cart.rice === 2 && G().orders.length === 0, 'an unaffordable order fails, charges nothing and keeps the cart');
eco().credit(100_000, 'top up'); clearGuard();
const expected = cartTotals().total, m1 = eco().money;
const r = checkout();
ok(r.ok && eco().money === m1 - expected && /^GRO-\d{4}$/.test((r as any).id), 'checkout charges exactly the order total once');
ok(eco().transactions[0].amount === -expected && eco().transactions[0].ref?.id === (r as any).id && eco().transactions[0].kind === 'food', 'the ledger entry equals the order total and points at the order');
ok(G().orders.length === 1 && G().orders[0].total === expected && G().orders[0].lines.reduce((s, l) => s + l.qty * l.unitPrice, 0) === G().orders[0].subtotal && G().orders[0].status === 'preparing' && Object.keys(G().cart).length === 0, 'the order records its lines and totals, and the cart is cleared');
ok(!checkout().ok && eco().money === m1 - expected, 'checking out an empty cart again charges nothing');
setQty('rice', 1); setQty('eggs', 1); const dup1 = checkout(), money2 = eco().money; setQty('rice', 1); setQty('eggs', 1); const dup2 = checkout();
ok(dup1.ok && !dup2.ok && eco().money === money2 && G().orders.length === 2, 'tapping Confirm twice with the same cart creates only one order');
console.log('Delivery');
const o = G().orders[1], pantry0 = { ...G().pantry };
useClockStore.setState({ minutes: o.placedAt + GROCERY.preparingMinutes }); runGrocery();
ok(G().orders.find((x) => x.id === o.id)!.status === 'on_the_way', 'after a few minutes it is on the way');
useClockStore.setState({ minutes: Math.max(...G().orders.map((x) => x.deliverAt)) }); runGrocery();
const afterOnce = JSON.stringify(G().pantry); for (let i = 0; i < 4; i++) runGrocery();
ok(G().orders.every((x) => x.status === 'delivered') && G().pantry.rice === (pantry0.rice ?? 0) + 2 + 1 && JSON.stringify(G().pantry) === afterOnce, 'both orders (rice 2 + rice 1) are added to the pantry once; running delivery again changes nothing');
ok(eco().transactions.filter((x) => x.ref?.id === o.id).length === 1, 'delivery moves no money');

console.log('Ride');
fresh();
const nearby = getDestination('amala')!;
ok(DESTINATIONS.length >= 14 && METHODS.length === 6 && DESTINATIONS.every((d) => d.activities.length > 0), '14+ destinations and six travel methods');
ok(travelBlocker('nope', 'keke') !== null && travelBlocker('wuse', 'keke')?.includes('Intercity') === true && travelBlocker('amala', 'own') === 'You do not own a car.', 'unknown places, other cities and a missing car are refused');
const m0 = eco().money, c0 = useClockStore.getState().minutes;
ok(travel('amala', 'keke').ok && eco().money === m0 - 500 && useClockStore.getState().minutes === c0 + 8 && useRideStore.getState().at === 'amala', 'a Keke trip charges the fare once, takes the trip time and arrives');
ok(eco().transactions[0].amount === -500 && eco().transactions[0].label === 'Keke to Iya Basira Amala Spot', 'the fare is in the ledger');
clearGuard(); ok(!travel('amala', 'cab').ok, 'you cannot travel to where you already are');
const act = nearby.activities.find((a) => a.id === 'amala')!;
st().apply({ hunger: -80 }); const h0 = st().stats.hunger, m2 = eco().money;
ok(doActivity('amala', act).ok && eco().money === m2 - 3_800 && st().stats.hunger > h0, 'an activity there charges its price and applies its effects');
clearGuard(); ok(!doActivity('quilox', DESTINATIONS.find((d) => d.id === 'quilox')!.activities[0]).ok, 'activities need you to be at the place');
ok(goHome().ok && useRideStore.getState().at === null && !goHome().ok, 'you can head home once');
clearGuard(); eco().debit(eco().money - 100, 'spend');
ok(!travel('freedom', 'cab').ok && useRideStore.getState().at === null && eco().money === 100, 'an unaffordable fare fails and changes nothing');
ok(travel('freedom', 'walk').ok && eco().money === 100, 'trekking is free');
useVehicleStore.getState().add('corolla'); clearGuard(); goHome(); clearGuard();
ok(travelBlocker('balogun', 'own') === null && travel('balogun', 'own').ok, 'your own car works once you own one');

console.log('Games lobby');
fresh();
const tables = tablesFor('lagos', 3);
ok(tables.length === 4 && tables.every((x) => x.game === 'Ludo' && x.seated >= 1 && x.seated <= x.max && x.max >= 2) && JSON.stringify(tablesFor('lagos', 3)) === JSON.stringify(tables), 'tables are deterministic for a city and day, with valid capacity');
const open = tables.find((x) => x.status === 'waiting')!;
const gm = eco().money;
ok(joinTable(open).ok && useGamesStore.getState().seat?.tableId === open.id && eco().money === gm, 'joining a waiting table takes a seat and charges nothing');
ok(!joinTable(open).ok, 'a second seat is refused while seated');
leaveTable(); ok(useGamesStore.getState().seat === null, 'you can leave');
const rich = tables.find((x) => x.wager > 0 && x.status === 'waiting');
if (rich) { eco().debit(eco().money, 'spend'); ok(!joinTable(rich).ok && useGamesStore.getState().seat === null, 'you cannot sit if you could not afford the stake'); }

console.log('Boutique');
fresh(50_000);
const { buyAndWear, isOwned } = await import('../src/game/boutique');
const { BOUTIQUE } = await import('../src/data/clothing');
const { occasionsOf, OCCASIONS, SHOP_CATEGORIES, canPreview } = await import('../src/data/boutiqueMeta');
const { useCharacterStore } = await import('../src/stores/characterStore');
const cheap = BOUTIQUE.find((b) => b.slot === 'top' && b.price > 0 && b.price < 20_000)!, dear = BOUTIQUE.find((b) => b.price > 100_000)!, bag = BOUTIQUE.find((b) => b.slot === 'bag')!;
ok(BOUTIQUE.every((b) => occasionsOf(b).length > 0 && occasionsOf(b).every((o) => OCCASIONS.some((x) => x.id === o))), 'every item has valid occasion tags');
ok(SHOP_CATEGORIES.map((c) => c.id).join() === 'clothes,shoes,bags,wigs,accessories' && SHOP_CATEGORIES.every((c) => BOUTIQUE.some((b) => c.slots.includes(b.slot))), 'the five brief categories each have items');
ok(OCCASIONS.map((o) => o.id).join() === 'Home,Sleep,Date Night,Party,Work,Gym,Everyday', 'the seven occasion filters match the brief');
const w0 = eco().money, n1 = eco().transactions.length;
ok(!buyAndWear(dear.id).ok && eco().money === w0 && eco().transactions.length === n1 && !isOwned(dear), 'an unaffordable item fails: no charge, not owned');
const r1 = buyAndWear(cheap.id);
ok(r1.ok && (r1 as any).bought && eco().money === w0 - cheap.price && isOwned(cheap) && useCharacterStore.getState().ownedClothes.includes(cheap.id), 'buying deducts the price once and adds it to the wardrobe');
ok(!buyAndWear(cheap.id).ok, 'a double tap is ignored'); clearGuard();
const r2 = buyAndWear(cheap.id);
ok(r2.ok && !(r2 as any).bought && eco().money === w0 - cheap.price && eco().transactions.length === n1 + 1, 'wearing an item you own again never charges');
