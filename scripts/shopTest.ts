import { startNewLife } from '../src/game/life';
import { joinTable, leaveTable, tablesFor } from '../src/game/games';
import { useClockStore } from '../src/stores/clockStore';
import { useEconomyStore } from '../src/stores/economyStore';
import { useGroceryStore } from '../src/stores/groceryStore';
import { useRideStore } from '../src/stores/rideStore';
