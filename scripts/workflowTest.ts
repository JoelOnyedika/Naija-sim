import './mockStorage';
import { registerContent } from '../src/content';
import { animFor, DEFAULT_WORK } from '../src/world/animations';
import { interruptActivity } from '../src/game/interrupt';
import { enterLandmark } from '../src/game/interiors';
import { startNewLife } from '../src/game/life';
import { useStatsStore } from '../src/stores/statsStore';
import { useInteriorStore } from '../src/stores/interiorStore';

registerContent();
let fails = 0;
const ok = (c: boolean, m: string) => { console.log(`${c ? '✓' : '✗'} ${m}`); if (!c) fails++; };
console.log('Animations');
ok(animFor('v_pallet', 'v_pallet:load_cargo', 'idle') === 'lift', 'loading cargo lifts');
ok(animFor('v_pc_desk', 'v_pc_desk:repair_phone', 'idle') === 'hammer', 'repairing hammers');
ok(animFor('v_altar', 'v_altar:pray', 'idle') === 'pray', 'praying prays');
ok(animFor('v_stall', 'v_stall:haggle', 'idle') === 'talk', 'haggling talks');
ok(animFor('v_dish_bay', 'v_dish_bay:mop_floor', 'idle') === 'sweep', 'mopping sweeps');
ok(animFor('v_gym_bench', 'v_gym_bench:lift_weights', 'idle') === 'curl', 'weights curl');
ok(animFor('v_kiosk', 'v_kiosk:buy_snack', 'idle') === 'eat', 'a snack is eaten');
ok(animFor('v_unknown_thing', 'v_unknown_thing:something_odd', 'idle') === DEFAULT_WORK, 'anything unknown gets the default work animation');
ok(animFor(undefined, undefined, 'idle') === 'work', 'no activity key still works');
ok(animFor('desk', 'desk:learn_code', 'type') === 'type', 'an object that already has an action keeps it');
console.log('Interrupting');
startNewLife('lapo');
useStatsStore.getState().start({ label: 'Load cargo', seconds: 30, effects: {}, pose: 'stand', kind: 'use' });
ok(!!useStatsStore.getState().activity, 'an activity is running');
const r = enterLandmark('lagos.apapa-port');
ok(r.ok, 'going to another venue is allowed while busy');
ok(useStatsStore.getState().activity === null, 'and it stopped the activity');
ok(useInteriorStore.getState().current !== null, 'you are in the new venue');
ok(!interruptActivity(), 'nothing to interrupt returns false');
console.log(fails ? `\n${fails} FAILED` : '\nall passed'); process.exit(fails ? 1 : 0);
