import './mockStorage';
import { registerContent } from '../src/content';
import { APPS } from '../src/data/apps';
import { CATEGORIES } from '../src/data/phoneLayout';
import { LENDERS, LENDER_IDS, LOAN_RULES } from '../src/data/loans';
import { chooseVisit, finishVisit, hunter, maybeCollectors, oddsOf, stepCollectors } from '../src/game/collectors';
import { isJailed } from '../src/game/crime';
import { activeLoan, anyOverdue, borrow, huntedLoans, lateFee, limitFor, owedOn, quote, repay, seize, totalOwed, whyNotBorrow } from '../src/game/loans';
import { startNewLife } from '../src/game/life';
import { useClockStore } from '../src/stores/clockStore';
import { useEconomyStore } from '../src/stores/economyStore';
import { useJailStore } from '../src/stores/jailStore';
import { useLoanStore } from '../src/stores/loanStore';

registerContent();
let fails = 0;
const ok = (c: boolean, m: string) => { console.log(`${c ? '✓' : '✗'} ${m}`); if (!c) fails++; };
const E = () => useEconomyStore.getState(), L = () => useLoanStore.getState();
const at = (min: number) => useClockStore.setState({ minutes: min });
const fresh = () => { startNewLife('lapo'); at(8 * 60); };
const setMoney = (n: number) => { const d = n - E().money; if (d > 0) E().credit(d, 'test', 'income'); else if (d < 0) E().debit(-d, 'test', 'purchase'); };
const D = LOAN_RULES.dayMinutes;
// rnd sequence for a visit: chance roll, men roll, police roll (0.9 = no police, 0.1 = police)
const seq = (...v: number[]) => { let i = 0; return () => v[Math.min(i++, v.length - 1)]; };

console.log('The three apps');
ok(LENDER_IDS.length === 3, 'three lenders');
ok(LENDERS.ofay.name === 'OFAY' && LENDERS.falmfay.name === 'FALMFAY', 'OFAY and FALMFAY');
ok(LENDER_IDS.every((id) => APPS.some((a) => a.id === id)) && LENDER_IDS.every((id) => CATEGORIES.some((c) => c.apps.includes(id))), 'each is an app on the phone and in the library');
ok(LENDER_IDS.every((id) => LENDERS[id].interest >= 0.2 && LENDERS[id].interest <= 0.3), 'interest is between 20% and 30%');
ok(new Set(LENDER_IDS.map((id) => LENDERS[id].interest)).size === 3, 'each lender charges differently');

console.log('Borrowing');
fresh(); setMoney(0);
ok(limitFor('ofay') === 20_000 && limitFor('falmfay') === 50_000 && limitFor('kwikkash') === 10_000, 'new customer limits');
ok(quote('ofay', 20_000).total === 24_000 && quote('falmfay', 40_000).total === 50_000 && quote('kwikkash', 10_000).total === 13_000, 'amount + 20/25/30% interest');
ok(whyNotBorrow('ofay', 20_001) !== null && whyNotBorrow('ofay', 500) !== null && whyNotBorrow('ofay', 20_000) === null, 'over the limit or under the minimum is refused');
const r = borrow('ofay', 20_000);
ok(r.ok && E().money === 20_000, 'the money arrives at once');
ok(!borrow('ofay', 1_000).ok, 'only one loan at a time per app');
ok(borrow('kwikkash', 10_000).ok && E().money === 30_000, 'a second app can lend at the same time');
ok(totalOwed() === 24_000 + 13_000, 'what you owe adds up');

console.log('Paying back');
const loan = activeLoan('ofay')!;
ok(loan.dueAt - loan.takenAt === 3 * D, 'OFAY gives 3 game days');
const part = repay(loan.id, 10_000);
ok(part.ok && owedOn(activeLoan('ofay')!) === 14_000 && !part.cleared, 'part payment lowers what is owed');
setMoney(30_000);
const full = repay(loan.id);
ok(full.ok && full.cleared && !activeLoan('ofay') && limitFor('ofay') === 32_000, 'on-time repayment clears it and raises the limit (20k to 32k)');
ok(whyNotBorrow('ofay', 32_000) === null && whyNotBorrow('ofay', 33_000) !== null, 'the new limit applies');
setMoney(0);
ok(!repay(activeLoan('kwikkash')!.id).ok, 'you cannot pay from an empty wallet');

console.log('Being late');
fresh(); setMoney(0); borrow('falmfay', 40_000);
const f = activeLoan('falmfay')!;
at(f.dueAt + 1);
ok(anyOverdue() && lateFee(f) === Math.round(0.04 * 40_000), 'one day late: 4% of the loan');
at(f.dueAt + 100 * D);
ok(lateFee(f) === Math.round(LENDERS.falmfay.lateCap * 40_000), 'late fees stop at the cap');
at(f.dueAt + 1);
ok(whyNotBorrow('ofay', 5_000) !== null, 'with an overdue loan you cannot borrow anywhere');
setMoney(100_000); repay(f.id);
ok(limitFor('falmfay') === 50_000 && L().record.falmfay.late === 1, 'a late repayment does not raise the limit');

console.log('Collectors');
fresh(); setMoney(0); borrow('kwikkash', 10_000); const k = activeLoan('kwikkash')!;
at(k.dueAt + 100);
ok(huntedLoans().length === 0 && hunter() === null, 'just overdue: nobody comes yet');
ok(!maybeCollectors('home', undefined, () => 0), 'and no visit happens');
at(k.dueAt + LOAN_RULES.huntAfterMinutes);
ok(huntedLoans().length === 1 && hunter()?.lender === 'kwikkash', 'overdue half a day: the lender hunts you');
ok(!maybeCollectors('home', undefined, () => 0.31), 'a roll of 31% does not trigger (chance is 30%)');
ok(maybeCollectors('home', undefined, seq(0.1, 0, 0.9), 1_000_000_000_000), 'a roll under 30% sends them');
ok(L().visit?.lender === 'kwikkash' && L().visit!.where === 'home', 'the visit is on screen');
ok(!maybeCollectors('home', undefined, () => 0), 'only one visit at a time');
ok(chooseVisit('hide', () => 0.49)?.tone === 'good' && L().visit?.result?.choice === 'hide', 'hiding works on a roll under 50%');
ok(chooseVisit('run') === null, 'you cannot choose twice');
finishVisit();
ok(!maybeCollectors('home', undefined, () => 0, Date.now() + 1000), 'after a visit they leave you alone for a while');
ok(maybeCollectors('home', undefined, seq(0, 0, 0.9), Date.now() + (LOAN_RULES.cooldownSeconds + 5) * 1000), 'and come back after the cooldown');
finishVisit();

console.log('Visit outcomes');
const visit = (rnd: () => number, where: 'home' | 'street' = 'home') => { L().set({ visit: null, lastVisitAt: 0 }); return maybeCollectors(where, undefined, rnd, 5_000_000_000_000); };
setMoney(5_000);
ok(visit(seq(0.1, 0, 0.9)) && !L().visit!.police, 'a visit without police');
const owed = L().visit!.owed;
ok(owed === owedOn(activeLoan('kwikkash')!) && owed > 13_000, 'they ask for the loan plus late fees');
const lose = chooseVisit('hide', () => 0.99);
ok(lose?.tone === 'bad' && E().money < 5_000 && !isJailed(), 'failing to hide without police: beaten and robbed, not jailed');
finishVisit();
setMoney(100_000);
ok(visit(seq(0.1, 0, 0.9)), 'visit again');
const pay = chooseVisit('pay');
ok(pay?.tone === 'good' && !activeLoan('kwikkash') && E().money < 100_000, 'paying clears the loan');
finishVisit();
fresh(); setMoney(0); borrow('ofay', 20_000); at(activeLoan('ofay')!.dueAt + LOAN_RULES.huntAfterMinutes + 5);
ok(visit(seq(0.1, 0, 0.1)) && L().visit!.police, 'a visit with police (roll under 30%)');
const ph = oddsOf('hide', L().visit!);
ok(ph === 0.35, 'hiding is harder with police (35%)');
ok(oddsOf('run', L().visit!) > oddsOf('fight', L().visit!), 'running beats fighting');
chooseVisit('hide', () => 0.99);
ok(isJailed() && useJailStore.getState().sentence?.minutes === LOAN_RULES.jailMinutes, 'police catch you: jailed for 10 minutes');
useJailStore.getState().patch({ sentence: null }); finishVisit();

console.log('Running and the street');
fresh(); setMoney(0); borrow('falmfay', 50_000); at(activeLoan('falmfay')!.dueAt + LOAN_RULES.huntAfterMinutes + 5);
visit(seq(0.1, 0, 0.9), 'street');
ok(chooseVisit('hide', () => 0) === null && L().visit?.result === null, 'hiding is only for home');
const rv = oddsOf('run', L().visit!), fv = oddsOf('fight', L().visit!);
ok(rv > fv && rv <= 0.92, `run odds ${Math.round(rv * 100)}% are above fight odds ${Math.round(fv * 100)}%`);
ok(chooseVisit('run', () => 0)?.tone === 'good', 'a good roll gets you away');
finishVisit();
L().set({ visit: null, lastVisitAt: 0 });
let went = false; ok(maybeCollectors('street', () => { went = true; }, seq(0.1, 0, 0.9), 9_000_000_000_000) && L().visit?.where === 'street', 'the street roll starts a street visit');
chooseVisit('pay'); finishVisit(); ok(went, 'after the visit the trip carries on');

console.log('Timer roll and seizing');
L().set({ visit: null, lastVisitAt: 0, lastRollAt: 0 });
stepCollectors(10_000_000_000_000, () => 0.9);
ok(L().visit === null && L().lastRollAt === 10_000_000_000_000, 'the timer rolls once, no hit at 90%');
stepCollectors(10_000_000_000_000 + 1000, () => 0);
ok(L().visit === null, 'it does not roll again inside the window');
stepCollectors(10_000_000_000_000 + (LOAN_RULES.rollSeconds + 1) * 1000, () => 0.05);
ok(L().visit !== null, 'next window, a low roll sends them wherever you are');
L().set({ visit: null });
setMoney(1_000); const took = seize(50_000);
ok(took === 1_000 && E().money === 0, 'seizing never takes more than the wallet');
fresh();
ok(L().loans.length === 0 && L().visit === null, 'a new life wipes loans and visits');
console.log(fails ? `\n${fails} FAILED` : '\nall passed'); process.exit(fails ? 1 : 0);
